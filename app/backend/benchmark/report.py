"""Render and write the benchmark report (docs/benchmark.md) and its evidence JSON."""

import json
from collections.abc import Mapping
from pathlib import Path
from typing import Final

from benchmark.metrics import BenchmarkSummary
from benchmark.runner import CaseResult

METRIC_LABELS: Final = {
    "top1_all": "Top-1 accuracy (all leak cases)",
    "top1_conclusive": "Top-1 accuracy (conclusive leak cases)",
    "top3_all": "Top-3 accuracy (all leak cases)",
    "rate_rel_error_median": "Rate error, median (relative)",
    "rate_rel_error_p90": "Rate error, 90th percentile (relative)",
    "inconclusive_rate": "Inconclusive rate (leak cases)",
    "false_call_rate": "False-call rate (no-leak cases)",
}

_METHOD: Final = (
    "Test leaks are generated with the truth model, which differs on purpose from the inversion "
    "physics: Pasquill-Gifford/Martin dispersion coefficients (the inversion uses Briggs rural), "
    "wind meander, gusty wind speed, building-wake dilution and sensor noise. Some sources are "
    "off-list: 2 to 10 m from a candidate, so no candidate is exactly right. The background of "
    "each sensor is estimated as the 5th percentile of its 10-minute means. A leak case is "
    "correct when the true candidate (on-list) or a candidate within 10 m of the true source "
    "(off-list) is ranked first (top-1) or in the first three (top-3), with the no-source "
    "hypothesis removed; an inconclusive result counts as wrong. Rate error uses only "
    "conclusive, top-1-correct cases. Cases, seeds, thresholds and coefficients are fixed "
    "before the run and are not tuned to the results; the numbers above are exactly what the "
    "run produced. The station and all data are simulated (evidence label: synthetic)."
)


def _fmt(value: float | None) -> str:
    """Format a metric with 3 significant figures; an em dash for None."""
    return "—" if value is None else f"{value:.3g}"


def results_table(summary: BenchmarkSummary) -> str:
    """The headline metrics as a Markdown table.

    Args:
        summary: The benchmark summary.

    Returns:
        A ``| Metric | Value |`` table, one row per entry of ``METRIC_LABELS``.
    """
    values = summary.model_dump()
    rows = [f"| {label} | {_fmt(values[key])} |" for key, label in METRIC_LABELS.items()]
    return "\n".join(["| Metric | Value |", "|---|---|", *rows])


def _split_table(first_column: str, split: Mapping[str, Mapping[str, float]]) -> str:
    """A Markdown table of one split (stability class or leak size)."""
    header = f"| {first_column} | Cases | Top-1 accuracy (all) | Inconclusive rate |"
    rows = [
        f"| {name} | {int(v['n'])} | {_fmt(v['top1_all'])} | {_fmt(v['inconclusive_rate'])} |"
        for name, v in split.items()
    ]
    return "\n".join([header, "|---|---|---|---|", *rows])


def _run_table(meta: Mapping[str, str]) -> str:
    """A Markdown table of the run metadata."""
    rows = [f"| {key.replace('_', ' ')} | {value} |" for key, value in meta.items()]
    return "\n".join(["| Item | Value |", "|---|---|", *rows])


def render_markdown(summary: BenchmarkSummary, meta: Mapping[str, str]) -> str:
    """Render the benchmark report.

    Args:
        summary: The benchmark summary.
        meta: Run metadata shown in the "Run" table (seed, revision, date, coefficients, counts).

    Returns:
        The Markdown text, LF line endings, ending with a newline.
    """
    parts = [
        "# PlumeTrace inversion benchmark",
        "## Run",
        _run_table(meta),
        "## Results",
        results_table(summary),
        "## By stability class",
        _split_table("Stability class", summary.by_stability),
        "## By leak size",
        _split_table("Leak size (kg/h)", summary.by_size),
        "## Method",
        _METHOD,
        "Generated by `python -m benchmark`; do not edit by hand.",
    ]
    return "\n\n".join(parts) + "\n"


def _case_row(cr: CaseResult) -> dict[str, object]:
    """One case as a JSON-ready row."""
    r = cr.result
    return {
        "case_id": cr.case.case_id,
        "kind": cr.case.kind,
        "true_candidate_id": cr.case.true_candidate_id,
        "true_rate_kg_h": cr.true_rate_kg_h,
        "top_id": r.top_id,
        "top_probability": r.top_probability,
        "inconclusive": r.inconclusive,
        "reason": r.reason,
        "rate_kg_h": r.rate_kg_h,
    }


def write_reports(
    summary: BenchmarkSummary,
    results: list[CaseResult],
    meta: Mapping[str, str],
    out_md: Path,
    out_json: Path,
) -> None:
    """Write the Markdown report and the evidence JSON (UTF-8, LF line endings).

    Args:
        summary: The benchmark summary.
        results: Every case result, for the evidence file.
        meta: Run metadata.
        out_md: Path of the Markdown report.
        out_json: Path of the evidence JSON; missing parent folders are created.
    """
    doc = {
        "meta": dict(meta),
        "summary": summary.model_dump(),
        "cases": [_case_row(cr) for cr in results],
    }
    out_md.parent.mkdir(parents=True, exist_ok=True)
    out_json.parent.mkdir(parents=True, exist_ok=True)
    out_md.write_bytes(render_markdown(summary, meta).encode("utf-8"))
    out_json.write_bytes((json.dumps(doc, sort_keys=True, indent=2) + "\n").encode("utf-8"))
