"""Render and write the before/after comparison report and its evidence JSON.

The Markdown (``docs/benchmark-improvement.md``) and the JSON are generated by
``python -m benchmark.compare`` and never edited by hand.
"""

import json
from collections.abc import Mapping
from pathlib import Path
from typing import Final

from benchmark.calibration import RELIABILITY_BINS, MethodMetrics
from benchmark.cases import BENCHMARK_SEED
from benchmark.metrics import is_correct
from benchmark.report import METRIC_LABELS
from benchmark.runner import CaseResult
from plumetrace.engineering.geometry import Point3

TASK8_LABEL: Final = "Task 8 inversion (narrow plume)"
MEANDER_LABEL: Final = "Meander-aware inversion"
NOT_RECORDED: Final = "not recorded"
PRE_REGISTERED: Final = "2026-11-14"
PUBLISHED_REVISION: Final = "23b8703"

CALIBRATION_LABELS: Final = {
    "confident_wrong_rate": "Confident-wrong rate (named cases wrong with p >= 0.95)",
    "missed_leak_rate": "Missed-leak rate (conclusive NONE on a leak case)",
    "rate_in_interval": "Rate inside the 90 % interval (good cases)",
    "grid_edge_share": "Rate at the grid edge (good cases)",
    "median_rate_ratio": "Median rate / true rate (good cases)",
}

_METHOD_TEXT: Final = (
    "The Task 8 inversion assumes a narrow plume along the 10-minute mean wind direction. The "
    "meander-aware inversion also receives, for every window, the circular standard deviation of "
    "the 10 s met-mast wind direction, and widens the horizontal spread of the plume: "
    "sigma_y,eff squared is sigma_y squared plus (x times the spread in radians) squared, with "
    "sigma_z unchanged (a project derivation, see docs/reference/ENGINEERING.md). The spread is "
    "measured from the data; the truth model's setting is never used. Both methods run on the "
    "same cases and the same generated data (each case seeds its own generator), so the "
    "comparison is paired. The fresh seed had never been run before this report; the metric "
    "definitions, the adoption rule and all other values were fixed in advance "
    f"(pre-registered {PRE_REGISTERED}) and are not tuned to the results. The published "
    f"column is the run of seed {BENCHMARK_SEED} at revision {PUBLISHED_REVISION}, which stays "
    "the unchanged 'before'. The benchmark uses no sensor faults or drift. Evidence label: "
    "synthetic (simulated station, simulated sensors). One seed: the sampling error on a "
    "proportion near 0.4 is about plus or minus 0.07."
)


def _num(value: float | None) -> str:
    """A number with 3 significant figures; an em dash for None."""
    return "—" if value is None else f"{value:.3g}"


def verdict_line(t8: MethodMetrics, m: MethodMetrics, adopted: bool) -> str:
    """The adoption verdict with the three compared numbers.

    Args:
        t8: Task 8 metrics on the fresh cases.
        m: Meander-aware metrics on the same cases.
        adopted: The outcome of ``adopt_meander``.

    Returns:
        One Markdown line, written by code from the numbers.
    """
    name = "meander-aware" if adopted else "Task 8 method"
    return (
        f"**Adopted for the app: {name}.** Rule: adopt the meander-aware method only if its "
        f"top-1 accuracy is at least Task 8's and its confident-wrong rate and false-call rate "
        f"are each at most Task 8's (ties adopt). Compared (meander-aware / Task 8): top-1 "
        f"{_num(m.top1_all)} / {_num(t8.top1_all)}; confident-wrong "
        f"{_num(m.confident_wrong_rate)} / {_num(t8.confident_wrong_rate)}; false-call "
        f"{_num(m.false_call_rate)} / {_num(t8.false_call_rate)}."
    )


def _table(header: list[str], rows: list[list[str]]) -> str:
    """A Markdown table."""
    lines = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    return "\n".join(lines + ["| " + " | ".join(row) + " |" for row in rows])


def _metric_tables(
    published: Mapping[str, float | None], t8: MethodMetrics, m: MethodMetrics
) -> str:
    """The published metrics in three columns, then the calibration rows."""
    head = ["Metric", f"Published (seed {BENCHMARK_SEED})", "Fresh Task 8", "Fresh meander-aware"]
    a, b = t8.summary.model_dump(), m.summary.model_dump()
    rows = [
        [label, _num(published.get(k)), _num(a[k]), _num(b[k])]
        for k, label in METRIC_LABELS.items()
    ]
    ca, cb = t8.calibration.model_dump(), m.calibration.model_dump()
    rows += [
        [label, NOT_RECORDED, _num(ca[k]), _num(cb[k])] for k, label in CALIBRATION_LABELS.items()
    ]
    return _table(head, rows)


def _reliability_table(t8: MethodMetrics, m: MethodMetrics) -> str:
    """Count and top-1 accuracy per probability bin for both methods."""
    head = ["Top probability", "Task 8 named", "Task 8 top-1", "Meander named", "Meander top-1"]
    rows = []
    for label, _, _ in RELIABILITY_BINS:
        a, b = t8.calibration.reliability[label], m.calibration.reliability[label]
        rows.append(
            [label, str(int(a["n"])), _num(a["accuracy"]), str(int(b["n"])), _num(b["accuracy"])]
        )
    return _table(head, rows)


def _split_table(
    title: str, a: Mapping[str, Mapping[str, float]], b: Mapping[str, Mapping[str, float]]
) -> str:
    """A split (stability class or leak size) for both methods side by side."""
    head = [
        title,
        "Cases (Task 8 / meander)",
        "Top-1 Task 8",
        "Top-1 meander",
        "Inconclusive Task 8",
        "Inconclusive meander",
    ]
    rows = []
    for name in sorted(set(a) | set(b)):
        x, y = a.get(name, {}), b.get(name, {})
        n = f"{int(x.get('n', 0))} / {int(y.get('n', 0))}"
        rows.append(
            [name, n] + [_num(d.get(k)) for k in ("top1_all", "inconclusive_rate") for d in (x, y)]
        )
    return _table(head, rows)


def _run_table(meta: Mapping[str, str]) -> str:
    """The run metadata as a Markdown table."""
    return _table(
        ["Item", "Value"],
        [
            ["seed", meta["seed"]],
            ["revision", meta["revision"]],
            ["date", meta["date"]],
            ["status", f"pre-registered {PRE_REGISTERED}"],
            ["mode", meta["mode"]],
            ["cases", meta["cases"]],
            ["method 1", TASK8_LABEL],
            ["method 2", MEANDER_LABEL],
        ],
    )


def render_markdown(
    meta: Mapping[str, str],
    published: Mapping[str, float | None],
    t8: MethodMetrics,
    m: MethodMetrics,
    adopted: bool,
) -> str:
    """Render the comparison report.

    Args:
        meta: Run metadata (``seed``, ``revision``, ``date``, ``mode``, ``cases``).
        published: The ``summary`` of the published benchmark JSON.
        t8: Task 8 metrics on the fresh cases.
        m: Meander-aware metrics on the same cases.
        adopted: The outcome of ``adopt_meander``.

    Returns:
        The Markdown text, LF line endings, ending with a newline.
    """
    parts = [
        "# PlumeTrace benchmark improvement round",
        "## Run",
        _run_table(meta),
        "## Results",
        _metric_tables(published, t8, m),
        "## Reliability of the stated probability (named cases)",
        _reliability_table(t8, m),
        "## By stability class",
        _split_table("Stability class", t8.summary.by_stability, m.summary.by_stability),
        "## By leak size",
        _split_table("Leak size (kg/h)", t8.summary.by_size, m.summary.by_size),
        "## Verdict",
        verdict_line(t8, m, adopted),
        "## Method",
        _METHOD_TEXT,
        "Generated by `python -m benchmark.compare`; do not edit by hand.",
    ]
    return "\n\n".join(parts) + "\n"


def _case_row(cr: CaseResult, method: str, positions: Mapping[str, Point3]) -> dict[str, object]:
    """One case result of one method as a JSON-ready row."""
    r, leak = cr.result, cr.case.source is not None
    return {
        "case_id": cr.case.case_id,
        "kind": cr.case.kind,
        "method": method,
        "true_candidate_id": cr.case.true_candidate_id,
        "true_rate_kg_h": cr.true_rate_kg_h,
        "top_id": r.top_id,
        "top_probability": r.top_probability,
        "rate_kg_h": r.rate_kg_h,
        "rate_p05_kg_h": r.rate_p05_kg_h,
        "rate_p95_kg_h": r.rate_p95_kg_h,
        "rate_at_grid_edge": r.rate_at_grid_edge,
        "inconclusive": r.inconclusive,
        "reason": r.reason,
        "correct_top1": is_correct(cr, 1, positions) if leak else None,
        "correct_top3": is_correct(cr, 3, positions) if leak else None,
    }


def write_compare_reports(
    meta: Mapping[str, str],
    methods: Mapping[str, tuple[MethodMetrics, list[CaseResult]]],
    published: Mapping[str, float | None],
    adopted: bool,
    positions: Mapping[str, Point3],
    out_md: Path,
    out_json: Path,
) -> None:
    """Write the Markdown report and the evidence JSON (UTF-8, LF line endings).

    Args:
        meta: Run metadata; written as is under ``meta`` in the JSON.
        methods: ``{"task8": (metrics, results), "meander": (metrics, results)}``.
        published: The ``summary`` of the published benchmark JSON.
        adopted: The outcome of ``adopt_meander``.
        positions: Candidate positions by id.
        out_md: Path of the Markdown report.
        out_json: Path of the evidence JSON; missing parent folders are created.
    """
    t8, m = methods["task8"][0], methods["meander"][0]
    doc = {
        "meta": dict(meta),
        "methods": {
            name: {
                "summary": metrics.summary.model_dump(),
                "calibration": metrics.calibration.model_dump(),
            }
            for name, (metrics, _) in methods.items()
        },
        "cases": [
            _case_row(cr, name, positions) for name, (_, rows) in methods.items() for cr in rows
        ],
    }
    out_md.parent.mkdir(parents=True, exist_ok=True)
    out_json.parent.mkdir(parents=True, exist_ok=True)
    out_md.write_bytes(render_markdown(meta, published, t8, m, adopted).encode("utf-8"))
    out_json.write_bytes((json.dumps(doc, sort_keys=True, indent=2) + "\n").encode("utf-8"))
