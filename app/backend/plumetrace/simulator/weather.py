"""The committed KS-07 weather snapshot: loading, validation and slicing.

The snapshot is generated by ``scripts/fetch_weather.py`` from Open-Meteo (CC BY 4.0) and
committed, so scenarios are reproducible offline. This module reads it; it never touches the
network.
"""

import json
from dataclasses import dataclass
from datetime import UTC, datetime
from pathlib import Path
from typing import Final

from plumetrace.engineering.truth_weather import HourlyWeather

DEFAULT_SNAPSHOT_PATH: Final[Path] = (
    Path(__file__).parent / "data" / "weather_ks07_2025-07-14_2025-07-20.json"
)


@dataclass(frozen=True)
class WeatherSnapshot:
    """A contiguous run of hourly weather with its source attribution.

    Attributes:
        start_utc: UTC time of ``hours[0]``.
        hours: Hourly weather, ``hour_index`` 0..n-1 with no gaps.
        attribution: Required data-source attribution text.
    """

    start_utc: datetime
    hours: list[HourlyWeather]
    attribution: str


def _require(doc: object, key: str) -> object:
    """Return ``doc[key]`` or raise a ``ValueError`` that names the missing key."""
    if not isinstance(doc, dict) or key not in doc:
        raise ValueError(f"weather snapshot is missing {key}")
    return doc[key]


def _parse_start(value: object) -> datetime:
    """Parse ``start_utc`` and require an explicit UTC offset."""
    try:
        start = datetime.fromisoformat(str(value))
    except ValueError as exc:
        raise ValueError(f"start_utc {value!r} is not an ISO 8601 time") from exc
    if start.tzinfo is None:
        raise ValueError(f"start_utc {value!r} has no UTC marker")
    return start.astimezone(UTC)


def _parse_hours(raw: object) -> list[HourlyWeather]:
    """Validate the hours: at least one, no null values, ``hour_index`` exactly 0..n-1."""
    if not isinstance(raw, list) or not raw:
        raise ValueError("weather snapshot has no hours")
    hours = [HourlyWeather.model_validate(item) for item in raw]
    if [h.hour_index for h in hours] != list(range(len(hours))):
        raise ValueError("hour_index values are not contiguous 0..n-1")
    return hours


def load_snapshot(path: Path = DEFAULT_SNAPSHOT_PATH) -> WeatherSnapshot:
    """Read and validate a weather snapshot file.

    Args:
        path: JSON file ``{"start_utc": "...Z", "attribution": "...", "hours": [...]}``;
            defaults to the committed KS-07 week.

    Returns:
        The snapshot.

    Raises:
        ValueError: On malformed JSON, a missing key, a naive ``start_utc``, a blank
            attribution, no hours, a null or unphysical value (including
            ``pydantic.ValidationError``) or ``hour_index`` values that are not 0..n-1.
    """
    doc = json.loads(path.read_text(encoding="utf-8"))
    start = _parse_start(_require(doc, "start_utc"))
    attribution = _require(doc, "attribution")
    if not isinstance(attribution, str) or not attribution.strip():
        raise ValueError("weather snapshot has a blank attribution")
    return WeatherSnapshot(start, _parse_hours(_require(doc, "hours")), attribution)


def slice_hours(snapshot: WeatherSnapshot, offset_h: int, hours: int) -> list[HourlyWeather]:
    """Return ``hours`` consecutive hours from ``offset_h``, re-indexed from 0.

    Args:
        snapshot: The loaded snapshot.
        offset_h: Hours to skip from the snapshot start (>= 0).
        hours: Number of hours wanted (>= 1).

    Returns:
        The slice, with ``hour_index`` 0..hours-1.

    Raises:
        ValueError: If ``offset_h`` is negative, ``hours`` is below 1, or the snapshot is
            too short.
    """
    if offset_h < 0 or hours < 1:
        raise ValueError(f"offset_h must be >= 0 and hours >= 1, got {offset_h} and {hours}")
    n = len(snapshot.hours)
    if n < offset_h + hours:
        raise ValueError(f"snapshot has {n} hours, need {offset_h + hours}")
    part = snapshot.hours[offset_h : offset_h + hours]
    return [h.model_copy(update={"hour_index": i}) for i, h in enumerate(part)]
