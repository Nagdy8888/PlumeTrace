"""Tests of the before/after comparison run: paired runs, determinism, files and the CLI."""

import json
import math
from pathlib import Path

import benchmark
import pytest
from benchmark.cases import BENCHMARK_SEED, N_ON_LIST, generate_cases
from benchmark.compare import main
from benchmark.report import METRIC_LABELS
from benchmark.runner import run_case

from plumetrace.facility.loader import load_facility

SPEC = load_facility()
# The fresh seed of the official run must never appear as a constant: it is built here only to
# search the sources for it.
FRESH_SEED_TEXT = "2026" + "1114"
PUBLISHED = {
    "summary": {key: 0.5 for key in METRIC_LABELS},
}
EXPECTED_METHODS = ("task8", "meander")


def _published(tmp: Path) -> Path:
    path = tmp / "published.json"
    path.write_text(json.dumps(PUBLISHED), encoding="utf-8")
    return path


def _is_date_line(line: bytes) -> bool:
    """The run date appears as a Markdown table row or a JSON key; nothing else may differ."""
    return line.startswith(b"| date |") or line.lstrip().startswith(b'"date":')


def _run(tmp: Path, name: str) -> tuple[Path, Path]:
    out_md, out_json = tmp / f"{name}.md", tmp / f"{name}.json"
    main(
        [
            "--seed",
            str(BENCHMARK_SEED),
            "--revision",
            "test",
            "--quick",
            "--published-json",
            str(_published(tmp)),
            "--out-md",
            str(out_md),
            "--out-json",
            str(out_json),
        ]
    )
    return out_md, out_json


@pytest.fixture(scope="module")
def first_run(tmp_path_factory: pytest.TempPathFactory) -> tuple[Path, Path]:
    """One quick comparison run on the published seed, shared by the file tests."""
    return _run(tmp_path_factory.mktemp("compare"), "a")


def test_meander_false_equals_the_default_run() -> None:
    """run_case(meander=False) is the unchanged benchmark path: same result as run_case()."""
    cases = generate_cases(SPEC, BENCHMARK_SEED)
    for case in (cases[0], cases[N_ON_LIST], cases[-1]):
        assert run_case(case, SPEC, meander=False) == run_case(case, SPEC)


def test_meander_true_returns_a_valid_finite_result() -> None:
    """run_case(meander=True) runs on a leak case and a no-leak case with finite fields."""
    cases = generate_cases(SPEC, BENCHMARK_SEED)
    for case in (cases[0], cases[-1]):
        r = run_case(case, SPEC, meander=True).result
        assert math.isfinite(r.top_probability) and r.windows_used > 0
        assert all(math.isfinite(s.probability) for s in r.ranked)
        if r.rate_kg_h is not None:
            assert math.isfinite(r.rate_kg_h) and r.rate_kg_h > 0.0


def test_comparison_writes_both_files(first_run: tuple[Path, Path]) -> None:
    """The quick run writes the Markdown report and the JSON evidence."""
    out_md, out_json = first_run
    md = out_md.read_text(encoding="utf-8")
    assert md.startswith("# ") and md.endswith("\n") and "\r" not in md
    assert "Generated by `python -m benchmark.compare`; do not edit by hand." in md
    assert "pre-registered 2026-11-14" in md
    assert "not recorded" in md
    assert ("Adopted for the app: meander-aware" in md) != (
        "Adopted for the app: Task 8 method" in md
    )
    doc = json.loads(out_json.read_text(encoding="utf-8"))
    assert set(doc) == {"meta", "methods", "cases"}
    assert set(doc["methods"]) == set(EXPECTED_METHODS)
    assert doc["meta"]["seed"] == str(BENCHMARK_SEED)
    assert doc["meta"]["pre_registered"] == "2026-11-14"
    assert doc["meta"]["adopted"] in EXPECTED_METHODS


def test_comparison_rows_cover_both_methods(first_run: tuple[Path, Path]) -> None:
    """Each of the 8 quick cases appears once per method with the specified fields."""
    doc = json.loads(first_run[1].read_text(encoding="utf-8"))
    rows = doc["cases"]
    assert len(rows) == 16
    assert {r["method"] for r in rows} == set(EXPECTED_METHODS)
    assert rows[0].keys() == {
        "case_id",
        "kind",
        "method",
        "true_candidate_id",
        "true_rate_kg_h",
        "top_id",
        "top_probability",
        "rate_kg_h",
        "rate_p05_kg_h",
        "rate_p95_kg_h",
        "rate_at_grid_edge",
        "inconclusive",
        "reason",
        "correct_top1",
        "correct_top3",
    }
    paired = {(r["case_id"], r["method"]) for r in rows}
    assert len(paired) == 16
    no_leak = [r for r in rows if r["kind"] == "no_leak"]
    assert all(r["correct_top1"] is None and r["correct_top3"] is None for r in no_leak)
    for method in EXPECTED_METHODS:
        assert set(doc["methods"][method]) == {"summary", "calibration"}


def test_two_runs_are_identical_apart_from_the_date(
    first_run: tuple[Path, Path], tmp_path: Path
) -> None:
    """The comparison is deterministic: both files match byte for byte except date lines."""
    second = _run(tmp_path, "b")
    for a, b in zip(first_run, second, strict=True):
        keep_a = [x for x in a.read_bytes().splitlines() if not _is_date_line(x)]
        keep_b = [x for x in b.read_bytes().splitlines() if not _is_date_line(x)]
        assert keep_a == keep_b and keep_a


def test_seed_is_required(capsys: pytest.CaptureFixture[str]) -> None:
    """There is no default seed: omitting --seed is an argparse error (exit status 2)."""
    with pytest.raises(SystemExit) as info:
        main(["--revision", "test"])
    assert info.value.code == 2
    assert "--seed" in capsys.readouterr().err


def test_fresh_seed_is_not_hard_coded() -> None:
    """No benchmark source file contains the fresh seed of the official run."""
    folder = Path(benchmark.__file__).parent
    sources = sorted(folder.glob("*.py"))
    assert any(p.name == "compare.py" for p in sources)
    assert all(FRESH_SEED_TEXT not in p.read_text(encoding="utf-8") for p in sources)
    tests = Path(__file__).parent
    for test_file in (Path(__file__), tests / "test_calibration.py"):
        assert FRESH_SEED_TEXT not in test_file.read_text(encoding="utf-8")
